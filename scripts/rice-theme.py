#!/usr/bin/env python3
"""Extract wallpaper colors with Matugen, render configs, then atomically activate.

Templates are immutable repository inputs. Generated files live in XDG_STATE_HOME,
so this never overwrites Home Manager's symlinks. Only successful generations are
selected; wallpaper paths are passed as arguments, never interpolated into shells.
"""
import argparse
import fcntl
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

ASSETS = Path(os.environ.get("RICE_THEME_ASSETS", Path(__file__).resolve().parents[1] / "assets"))
KEYS = ("primary", "on_primary", "secondary", "tertiary", "surface", "surface_container", "on_surface", "outline", "error")


def palette_valid(data):
    """Accept only RGB(A) literals, so generated Lua/CSS cannot contain injected code."""
    return {key: normalize_color(data[key]) for key in KEYS}


def normalize_color(value):
    if not isinstance(value, str) or not re.fullmatch(r"#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?", value):
        raise ValueError(f"Invalid palette color: {value!r}")
    return value[:7].lower()


def render(p, font, size):
    """One small renderer keeps all consumers on the same extracted palette."""
    # Font is local config, but reject delimiters that could damage generated configs.
    if not re.fullmatch(r"[\w .+-]+", font) or not 6 <= size <= 40:
        raise ValueError("Font must be a plain family name; size must be between 6 and 40")
    rgb = {k: v[1:] for k, v in p.items()}
    out = {}
    out["palette.json"] = json.dumps(p, indent=2) + "\n"
    out["hyprland.lua"] = (
        '-- Generated by rice-theme. Change the wallpaper or renderer, not this file.\n'
        'hl.config({ general = { col = { active_border = "rgb(' + rgb["primary"] + ')", '
        'inactive_border = "rgb(' + rgb["outline"] + ')" } } })\n'
    )
    out["waybar.css"] = '/* Wallpaper palette; imported by Waybar. */\n' + ''.join(
        f'@define-color {key} {value};\n' for key, value in p.items())
    out["rofi.rasi"] = f'''/* Wallpaper-derived launcher theme. */
* {{ background: {p['surface']}; foreground: {p['on_surface']}; accent: {p['primary']};
    background-color: @background; text-color: @foreground; }}
window {{ width: 600px; border: 2px; border-color: @accent; border-radius: 8px; padding: 16px; }}
mainbox {{ spacing: 12px; children: [ inputbar, listview ]; }}
inputbar {{ spacing: 8px; children: [ prompt, entry ]; }}
entry {{ placeholder: "Search applications"; }}
listview {{ lines: 8; scrollbar: false; }}
element {{ padding: 8px; border-radius: 4px; }}
element selected.normal {{ background-color: @accent; text-color: {p['on_primary']}; }}
element-text {{ background-color: inherit; text-color: inherit; }}
'''
    out["mako.conf"] = f'''# Wallpaper-derived notifications.
font={font} {size}
background-color={p['surface']}
text-color={p['on_surface']}
border-color={p['primary']}
border-size=2
border-radius=6
default-timeout=5000
width=350
anchor=top-right
'''
    # Semantic ANSI colors stay recognizable; accents follow the wallpaper.
    ansi = [rgb['surface'], 'ff8a80', 'a5d6a7', 'ffe082', rgb['primary'], rgb['tertiary'], rgb['secondary'], rgb['on_surface']]
    out["foot.ini"] = '# Generated palette. New Foot windows read this include.\n[colors]\n' + (
        f'background={rgb["surface"]}\nforeground={rgb["on_surface"]}\n'
    ) + ''.join(f'regular{i}={color}\nbright{i}={color}\n' for i, color in enumerate(ansi))
    # Named GTK colors cover GTK3 and many GTK4 widgets; apps can override styling.
    out["gtk.css"] = f'''/* Generated GTK colors; restart apps that cache their style. */
@define-color accent_color {p['primary']};
@define-color accent_bg_color {p['primary']};
@define-color accent_fg_color {p['on_primary']};
@define-color window_bg_color {p['surface']};
@define-color window_fg_color {p['on_surface']};
@define-color view_bg_color {p['surface']};
@define-color view_fg_color {p['on_surface']};
@define-color headerbar_bg_color {p['surface_container']};
@define-color headerbar_fg_color {p['on_surface']};
@define-color theme_bg_color {p['surface']};
@define-color theme_fg_color {p['on_surface']};
@define-color theme_base_color {p['surface']};
@define-color theme_text_color {p['on_surface']};
@define-color theme_selected_bg_color {p['primary']};
@define-color theme_selected_fg_color {p['on_primary']};
'''
    # Qt QPalette roles, in Qt's order, for qt5ct/qt6ct custom color schemes.
    roles = [p['on_surface'], p['surface_container'], p['outline'], p['outline'], p['outline'],
             p['outline'], p['on_surface'], p['on_surface'], p['on_surface'], p['surface'],
             p['surface'], '#000000', p['primary'], p['on_primary'], p['primary'], p['tertiary'],
             p['surface_container'], p['surface'], p['on_surface'], p['surface'], p['on_surface']]
    colors = ', '.join('#ff' + color[1:] for color in roles)
    out["qt.colors"] = '# Wallpaper-derived Qt palette.\n[ColorScheme]\n' + ''.join(
        f'{group}={colors}\n' for group in ('active_colors', 'inactive_colors', 'disabled_colors'))
    return out


def run_optional(command):
    """A stopped GUI service does not make a successfully generated palette invalid."""
    if shutil.which(command[0]):
        result = subprocess.run(command, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True)
        if result.returncode:
            print(f"Theme saved; reload skipped for {command[0]}: {result.stderr.strip()}", file=sys.stderr)


def reload_desktop():
    if not os.environ.get('WAYLAND_DISPLAY'):
        return
    run_optional(['hyprctl', 'reload'])
    run_optional(['systemctl', '--user', 'try-restart', 'waybar.service', 'mako.service', 'rice-wallpaper.service'])


def apply(image, state, font, size, reload=True):
    image = image.expanduser().resolve(strict=True)
    if not image.is_file():
        raise ValueError('Wallpaper must be a regular image file')
    state.mkdir(parents=True, exist_ok=True)
    with (state / 'lock').open('w') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        generations = state / 'generations'
        generations.mkdir(exist_ok=True)
        generation = Path(tempfile.mkdtemp(prefix='theme-', dir=generations))
        try:
            # Keep a private copy so moving/deleting the original wallpaper is harmless.
            with image.open('rb') as source:
                magic = source.read(12)
            suffix = '.png' if magic.startswith(b'\x89PNG\r\n\x1a\n') else (
                '.jpg' if magic.startswith(b'\xff\xd8\xff') else (
                    '.webp' if magic[:4] == b'RIFF' and magic[8:12] == b'WEBP' else None))
            if suffix is None:
                raise ValueError('Use a PNG, JPEG or WebP wallpaper')
            wallpaper = generation / ('image' + suffix)
            shutil.copyfile(image, wallpaper)
            (generation / 'wallpaper').symlink_to(wallpaper.name)
            config = generation / 'matugen.toml'
            config.write_text('[config]\nversion_check = false\n[templates.palette]\n'
                              f'input_path = {json.dumps(str(ASSETS / "palette.json.template"))}\n'
                              f'output_path = {json.dumps(str(generation / "palette.json"))}\n')
            subprocess.run(['matugen', '--config', str(config), 'image', str(wallpaper), '--mode', 'dark', '--source-color-index', '0'], check=True)
            p = palette_valid(json.loads((generation / 'palette.json').read_text()))
            for name, content in render(p, font, size).items():
                (generation / name).write_text(content)
            # Only commit once every output has been rendered successfully.
            candidate = state / 'current.new'
            candidate.unlink(missing_ok=True)
            candidate.symlink_to(generation)
            candidate.replace(state / 'current')
        except Exception:
            shutil.rmtree(generation)
            raise
        # Retain two previous theme generations; these are independent of OS generations.
        for old in sorted(generations.iterdir(), key=lambda p: p.stat().st_mtime, reverse=True)[3:]:
            if old.is_dir() and old != generation:
                shutil.rmtree(old)
    if reload:
        reload_desktop()
    print(f'Theme applied: {image}')


def choose(directory):
    """Use Rofi's numeric selection, so filenames cannot become shell commands."""
    images = sorted(p for p in directory.expanduser().rglob('*') if p.is_file()
                    and p.suffix.lower() in {'.png', '.jpg', '.jpeg', '.webp'})
    if not images:
        raise ValueError(f'No PNG/JPEG/WebP wallpapers in {directory}')
    labels = [str(p.relative_to(directory.expanduser())).replace('\n', ' ') for p in images]
    selected = subprocess.run(['rofi', '-dmenu', '-i', '-p', 'Wallpaper', '-format', 'i'],
                              input='\n'.join(labels), text=True, stdout=subprocess.PIPE)
    if selected.returncode:
        return None
    return images[int(selected.stdout.strip())]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['apply', 'choose', 'init', 'refresh'])
    parser.add_argument('image', nargs='?', type=Path)
    parser.add_argument('--no-reload', action='store_true', help='Generate without contacting GUI services')
    args = parser.parse_args()
    state = Path(os.environ.get('XDG_STATE_HOME', Path.home() / '.local/state')) / 'rice'
    config_home = Path(os.environ.get('XDG_CONFIG_HOME', Path.home() / '.config'))
    preferences = config_home / 'rice/settings.json'
    prefs = json.loads(preferences.read_text()) if preferences.exists() else {}
    font, size = prefs.get('font', 'JetBrainsMono Nerd Font'), prefs.get('fontSize', 11)
    if args.action == 'apply':
        if args.image is None:
            parser.error('apply requires an image path')
        image = args.image
    elif args.action == 'choose':
        image = choose(args.image or Path.home() / 'Pictures/Wallpapers')
        if image is None:
            return
    else:
        previous = state / 'current/wallpaper'
        image = previous if previous.exists() else ASSETS / 'default-wallpaper.png'
    apply(image, state, font, size, reload=not args.no_reload)


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as error:
        print(f'rice-theme: {error}', file=sys.stderr)
        sys.exit(1)
